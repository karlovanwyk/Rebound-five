/**
 * dom.ts: tiny helpers for building UI with plain DOM calls (no framework).
 *
 * The UI is small enough that a framework would add more to learn than it saves. Each
 * screen builds its elements with el() and wires up ordinary event listeners.
 */
export function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  className?: string,
  text?: string,
): HTMLElementTagNameMap[K] {
  const element = document.createElement(tag);
  if (className) element.className = className;
  if (text !== undefined) element.textContent = text;
  return element;
}

export function button(label: string, className: string, onClick: () => void): HTMLButtonElement {
  const b = el('button', className, label);
  b.type = 'button';
  b.addEventListener('click', onClick);
  return b;
}
